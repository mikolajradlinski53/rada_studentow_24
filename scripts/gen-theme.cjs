// Generates src/app/theme.css: light/dark mapping of the Tailwind palette.
const fs = require('fs');
const path = require('path');
const root = process.argv[2] || path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'node_modules/tailwindcss/theme.css'), 'utf8');

const pal = {};
for (const m of src.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) {
  (pal[m[1]] ??= {})[m[2]] = m[3].trim();
}

const STEPS = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];
// Light mode: dark-tuned tints/text flip to their light counterparts. 500/600 (solid
// fills, bars) stay; 400 (used as text on dark) maps to 600 so it reads on white.
const FLIP = { 50: '950', 100: '900', 200: '800', 300: '700', 400: '600', 500: '500', 600: '600', 700: '300', 800: '200', 900: '100', 950: '50' };
const TINTS = ['emerald', 'red', 'amber', 'sky', 'violet', 'green', 'yellow', 'rose'];

// Neutrals, hand-tuned (Apple system greys). Dark = near Tailwind zinc, slightly deeper.
const zincDark = {
  50: '#fafafa', 100: '#f4f4f5', 200: '#e4e4e7', 300: '#d4d4d8', 400: '#a1a1aa', 500: '#8a8a93',
  600: '#5c5c66', 700: '#3a3a40', 800: '#27272b', 900: '#18181b', 950: '#0b0b0d',
};
const zincLight = {
  950: '#f2f2f7', // grouped background
  900: '#ffffff', // cards / surfaces
  800: '#e9e9ee', // inputs, fills, hairlines
  700: '#d4d4da', // borders, active fills
  600: '#7c7c83', // placeholders, abstain fill
  500: '#6b6b72', // muted text
  400: '#55555b', // secondary text
  300: '#3a3a3e',
  200: '#2c2c30',
  100: '#1c1c1f', // primary text
  50: '#111113',
};

// Accent: Apple-like system blue instead of "AI indigo". Utilities keep the
// indigo-* names so no component churn; the hue is defined here once.
const accentDark = { ...pal.blue, 300: pal.blue['300'], 400: pal.blue['400'], 500: pal.blue['500'], 600: pal.blue['600'] };
const accentLight = Object.fromEntries(STEPS.map((s) => [s, pal.blue[FLIP[s]]]));
accentLight['600'] = pal.blue['600'];
accentLight['500'] = pal.blue['500'];

const decl = (name, map) => STEPS.map((s) => `  --color-${name}-${s}: ${map[s]};`).join('\n');

const darkBlock = [decl('zinc', zincDark), decl('indigo', accentDark)].join('\n');
const lightBlock = [
  decl('zinc', zincLight),
  decl('indigo', accentLight),
  ...TINTS.filter((t) => pal[t]).map((t) => decl(t, Object.fromEntries(STEPS.map((s) => [s, pal[t][FLIP[s]]])))),
].join('\n');
const defaultTints = TINTS.filter((t) => pal[t]).map((t) => decl(t, pal[t])).join('\n');

const css = `/* GENERATED by scripts/gen-theme.cjs (npm run theme). Do not edit by hand.
 *
 * Components are written against the dark palette (zinc-950 page, zinc-100 text,
 * emerald-900/40 tints...). In light mode the scales are remapped so the SAME
 * classes produce an Apple-style light UI (grouped grey background, white cards).
 * .theme-fixed pins the original palette for things that must not flip: the
 * projector (always dark) and printed paper documents.
 */

:root {
  color-scheme: dark;
${darkBlock}
}

@media (prefers-color-scheme: light) {
  :root {
    color-scheme: light;
${lightBlock.replace(/^/gm, '  ')}
  }
}

/* Explicit choice (profile setting) beats the system preference. */
:root[data-theme="light"] {
  color-scheme: light;
${lightBlock}
}
:root[data-theme="dark"] {
  color-scheme: dark;
${darkBlock}
${defaultTints}
}

.theme-fixed {
  color-scheme: dark;
${darkBlock}
${defaultTints}
}
`;
fs.writeFileSync(path.join(root, 'src/app/theme.css'), css);
console.log('wrote', css.length, 'bytes');
